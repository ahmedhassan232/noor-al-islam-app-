export function getDhikr(id: string): { dhikr: Dhikr; category: AdhkarCategory } | undefined {
  for (const c of ADHKAR) {
    const d = c.items.find((x) => x.id === id);
    if (d) return { dhikr: d, category: c };
  }
  return undefined;
}

export function getCategory(id: string): AdhkarCategory | undefined {
  return ADHKAR.find((c) => c.id === id);
}
